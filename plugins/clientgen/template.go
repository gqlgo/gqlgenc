package clientgen

import (
	_ "embed" // used to load template file
	"fmt"

	gqlgenconfig "github.com/99designs/gqlgen/codegen/config"
	"github.com/99designs/gqlgen/codegen/templates"

	"github.com/Yamashou/gqlgenc/v3/codegen"
	"github.com/Yamashou/gqlgenc/v3/config"
)

//go:embed template.tmpl
var template string

// Generate は、オペレーションごとの型付きの Operation 値を、設定の generate.client.file へ書き出す。
// gqlgenCfg は、import の解決に使うパッケージキャッシュを持つ gqlgen の設定。
func Generate(cfg *config.Config, gqlgenCfg *gqlgenconfig.Config, operations []*codegen.Operation) error {
	if err := templates.Render(templates.Options{
		PackageName:     cfg.ClientGen.Package,
		Template:        template,
		TemplateFS:      nil,
		Filename:        cfg.ClientGen.Filename,
		RegionTags:      false,
		GeneratedHeader: false,
		PackageDoc:      "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n",
		FileNotice:      "",
		Data: map[string]any{
			"QueryPackage":     cfg.QueryGen.Pkg().Name(),
			"QueryPackagePath": cfg.QueryGen.Pkg().Path(),
			"SamePackage":      cfg.ClientGen.ImportPath() == cfg.QueryGen.ImportPath(),
			"Operations":       operations,
		},
		Funcs:    nil,
		Packages: gqlgenCfg.Packages,
	}); err != nil {
		return fmt.Errorf("%s generating failed: %w", cfg.ClientGen.Filename, err)
	}

	return nil
}
