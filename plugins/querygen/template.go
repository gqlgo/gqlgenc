// Package querygen はカスタム UnmarshalJSON メソッドを持つ GraphQL クライアントのクエリ型を生成する。
//
// GraphQL オペレーション（クエリ、ミューテーション、サブスクリプション）用の Go 型と、
// 型安全な UnmarshalJSON メソッドを生成する。UnmarshalJSON メソッドは以下を処理する:
//   - Fragment spreads (json:"-" を持つ名前付きフィールド)
//   - Inline fragments (__typename に基づく型条件付きフィールド)
//   - ネストしたフィールド構造
//
// 生成されるコードは json/v2 を使用する。UnmarshalJSONFrom は
// フラグメントを含む型にのみ生成され、通常フィールドはメソッドを持たない別名型を
// 経由して json/v2 のデフォルトデコードに任せる。
package querygen

import (
	_ "embed" // used to load template file
	"fmt"
	"go/types"

	"github.com/99designs/gqlgen/codegen/templates"

	"github.com/Yamashou/gqlgenc/v3/codegen"
	"github.com/Yamashou/gqlgenc/v3/config"
)

//go:embed template.tmpl
var template string

// Generate は埋め込みテンプレートをレンダリングしてクエリ型ファイルを生成する。
//
// この関数は以下の処理を行う:
//  1. 型生成ロジックを扱う CodeGenerator を作成
//  2. オペレーションと型データでテンプレートをレンダリング
//  3. テンプレート関数 "genCode" と "needsJSONImport" を提供
//  4. 生成されたコードを設定されたファイル名に書き込み
//
// パラメータ:
//   - cfg: 出力場所とパッケージ名を指定する gqlgenc 設定
//   - operations: 生成ファイルに含める GraphQL オペレーション
//   - goTypes: コード生成対象の Go 型（オペレーションレスポンス型）
//
// テンプレートのレンダリングが失敗した場合はエラーを返す。
func Generate(cfg *config.Config, operations []*codegen.Operation, goTypes []types.Type) error {
	// 解析済みの型で CodeGenerator を作成
	codeGen := NewCodeGenerator(goTypes, cfg.GQLGencConfig.GenerateGetters)

	if err := templates.Render(templates.Options{
		PackageName:     cfg.GQLGencConfig.QueryGen.Package,
		Template:        template,
		TemplateFS:      nil,
		Filename:        cfg.GQLGencConfig.QueryGen.Filename,
		RegionTags:      false,
		GeneratedHeader: false,
		PackageDoc:      "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n",
		FileNotice:      "",
		Data: map[string]any{
			"GoTypes":    goTypes,
			"Operations": operations,
		},
		Funcs: map[string]any{
			"genCode": codeGen.Generate,
			"needsJSONImport": func() bool {
				return codeGen.NeedsJSONImport(goTypes)
			},
		},
		Packages: cfg.GQLGenConfig.Packages,
	}); err != nil {
		return fmt.Errorf("%s generating failed: %w", cfg.GQLGencConfig.QueryGen.Filename, err)
	}

	return nil
}
