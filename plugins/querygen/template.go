// Package querygen は、オペレーションのレスポンスの型を query_gen.go に生成する。
//
// codegen が作ったレスポンスの型 (codegen.ResponseType) を読み、型の宣言と、フラグメントを持つ型の
// UnmarshalJSONFrom / MarshalJSONTo を書く。選択の種類 (フィールド・フラグメントスプレッド・
// インラインフラグメント) は codegen が決めていて、このパッケージは判定し直さない。
//
// 生成するコードは json/v2 を使う。フラグメントのフィールド (json:"-") は既定のデコードでは値が
// 入らないため、フラグメントを持つ型にだけ UnmarshalJSONFrom を生成し、同じ JSON オブジェクトから
// フラグメントスプレッドと、__typename が型条件を満たすインラインフラグメントをデコードする。
package querygen

import (
	_ "embed" // used to load template file
	"fmt"
	"slices"

	gqlgenconfig "github.com/99designs/gqlgen/codegen/config"
	"github.com/99designs/gqlgen/codegen/templates"

	"github.com/Yamashou/gqlgenc/v3/codegen"
	"github.com/Yamashou/gqlgenc/v3/config"
)

//go:embed template.tmpl
var template string

// Generate は、レスポンスの型 responseTypes とオペレーションの Document 定数を、設定の
// generate.query.file へ書き出す。型ごとのコードは genCode が作る。gqlgenCfg は、import の解決に使う
// パッケージキャッシュを持つ gqlgen の設定。
func Generate(cfg *config.Config, gqlgenCfg *gqlgenconfig.Config, operations []*codegen.Operation, responseTypes []*codegen.ResponseType) error {
	if err := templates.Render(templates.Options{
		PackageName:     cfg.QueryGen.Package,
		Template:        template,
		TemplateFS:      nil,
		Filename:        cfg.QueryGen.Filename,
		RegionTags:      false,
		GeneratedHeader: false,
		PackageDoc:      "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n",
		FileNotice:      "",
		Data: map[string]any{
			"ResponseTypes": responseTypes,
			"Operations":    operations,
		},
		Funcs: map[string]any{
			"genCode": func(responseType *codegen.ResponseType) string {
				return genCode(responseType, cfg.GenerateGetters)
			},
			// UnmarshalJSONFrom / MarshalJSONTo を生成する型が 1 つでもあれば、json の import が要る
			"needsJSONImport": func() bool {
				return slices.ContainsFunc(responseTypes, hasFragment)
			},
		},
		Packages: gqlgenCfg.Packages,
	}); err != nil {
		return fmt.Errorf("%s generating failed: %w", cfg.QueryGen.Filename, err)
	}

	return nil
}
