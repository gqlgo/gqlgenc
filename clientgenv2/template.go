//go:embed template.gotpl
var template string

func RenderTemplate(cfg *config.Config, fragments []*Fragment, operations []*Operation, operationResponses []*OperationResponse, structSources []*StructSource, generateCfg *gqlgencConfig.GenerateConfig, client config.PackageConfig) error {
	genGettersGenerator := &GenGettersGenerator{
		ClientPackageName: client.Package,
	}

	// structDef spells field types with gqlgen's ref, not LookupType, because ref also writes interface{} as any.
	ref, ok := templates.Funcs()["ref"].(func(types.Type) string)
	if !ok {
		return fmt.Errorf("%s generating failed: gqlgen's ref template func has an unexpected type", client.Filename)
	}

	err := templates.Render(templates.Options{
		PackageName: client.Package,
		Filename:    client.Filename,
		Template:    template,
		Data: map[string]any{
			"Fragment":            fragments,
			"Operation":           operations,
			"OperationResponse":   operationResponses,
			"GenerateClient":      generateCfg.ShouldGenerateClient(),
			"StructSources":       structSources,
			"ClientInterfaceName": generateCfg.GetClientInterfaceName(),
		},
		Packages:   cfg.Packages,
		PackageDoc: "// Code generated by github.com/gqlgo/gqlgenc, DO NOT EDIT.\n",
		Funcs: map[string]any{
			"genGetters":           genGettersGenerator.GenFunc(),
			"genConversionGetters": genGettersGenerator.ConversionGettersFunc(fragments),
			"structDef": func(t types.Type) string {
				return structDef(t, ref)
			},
		},
	})
	if err != nil {
		return fmt.Errorf("%s generating failed: %w", client.Filename, err)
	}

	return nil
}

// structDef renders the Go type of a generated type declaration.
//
// Arguments:
//   - t: the type to render
//   - lookupType: renders a type that is not a struct, and each field type of
//     a struct; the template passes the `ref` template func
//
// Returns:
//   - string: the Go type expression; for a struct, written field by field so
//     that tags come out as raw string literals (`json:"id"`) instead of the
//     escaped form go/types prints ("json:\"id\"")
//
// Preconditions:
//   - none
//
// Postconditions:
//   - field types are spelled exactly as lookupType spells them
//   - a tag that itself contains a backtick keeps the quoted form
func structDef(t types.Type, lookupType func(types.Type) string) string {
	st, ok := t.(*types.Struct)
	if !ok {
		return lookupType(t)
	}

	var b strings.Builder

	b.WriteString("struct {\n")

	for i := range st.NumFields() {
		field := st.Field(i)
		if !field.Embedded() {
			b.WriteString(field.Name() + " ")
		}

		b.WriteString(lookupType(field.Type()))

		if tag := st.Tag(i); tag != "" {
			if strings.ContainsRune(tag, '`') {
				b.WriteString(" " + strconv.Quote(tag))
			} else {
				b.WriteString(" `" + tag + "`")
			}
		}

		b.WriteString("\n")
	}

	b.WriteString("}")

	return b.String()
}

type GenGettersGenerator struct {
	ClientPackageName string
}

func (g *GenGettersGenerator) GenFunc() func(name string, p types.Type) (string, error) {
	// This method returns a string of getters for a struct.
	// The idea is to be able to chain calls safely without having to check for nil.
	// To make this work we need to return a pointer to the struct if the field is a struct.
	return func(name string, p types.Type) (string, error) {
		var it *types.Struct

		it, ok := p.(*types.Struct)
		if !ok {
			return "", nil
		}

		var buf bytes.Buffer

		for field := range it.Fields() {
			returns, err := g.returnTypeName(field.Type(), false)
			if err != nil {
				return "", fmt.Errorf("getter %s.Get%s: %w", name, field.Name(), err)
			}

			buf.WriteString("func (t *" + name + ") Get" + field.Name() + "() " + returns + "{\n")
			buf.WriteString("if t == nil {\n t = &" + name + "{}\n}\n")

			pointerOrNot := ""
			if _, ok := field.Type().(*types.Named); ok {
				pointerOrNot = "&"
			}

			buf.WriteString("return " + pointerOrNot + "t." + field.Name() + "\n}\n")
		}

		return buf.String(), nil
	}
}

// ConversionGettersFunc returns a template function that generates conversion getters
// for spread fragments. Each getter constructs the original fragment type from the
// flattened parent struct's fields. ownerType is the parent fragment's struct type.
func (g *GenGettersGenerator) ConversionGettersFunc(allFragments []*Fragment) func(ownerName string, ownerType types.Type, spreads []*SpreadFragmentInfo) string {
	fragmentMap := make(map[string]*Fragment, len(allFragments))
	for _, f := range allFragments {
		fragmentMap[f.Name] = f
	}

	return func(ownerName string, ownerType types.Type, spreads []*SpreadFragmentInfo) string {
		if len(spreads) == 0 {
			return ""
		}

		var buf bytes.Buffer

		for _, spread := range spreads {
			targetStruct := resolveTargetFragment(fragmentMap, spread)
			if targetStruct == nil {
				continue
			}

			ownerStruct, _ := ownerType.(*types.Struct)
			if ownerStruct == nil {
				ownerStruct = underlyingStruct(ownerType)
			}

			g.writeConversionGetter(&buf, ownerName, ownerStruct, g.typeName(spread.Type), targetStruct)
		}

		return buf.String()
	}
}

// resolveTargetFragment looks up a spread fragment's definition and returns its
// underlying struct type, or nil if not found.
func resolveTargetFragment(fragmentMap map[string]*Fragment, spread *SpreadFragmentInfo) *types.Struct {
	targetFragment, ok := fragmentMap[spread.Name]
	if !ok {
		return nil
	}

	targetStruct, ok := targetFragment.Type.(*types.Struct)
	if !ok {
		return nil
	}

	return targetStruct
}

// writeConversionGetter writes a single conversion getter method that constructs
// the target fragment type from the owner struct's fields. ownerStruct may be nil
// when the owner's struct type is unknown.
func (g *GenGettersGenerator) writeConversionGetter(buf *bytes.Buffer, ownerName string, ownerStruct *types.Struct, targetTypeName string, targetStruct *types.Struct) {
	buf.WriteString("func (t *" + ownerName + ") Get" + targetTypeName + "() *" + targetTypeName + " {\n")
	buf.WriteString("if t == nil {\n t = &" + ownerName + "{}\n}\n")
	buf.WriteString("return &" + targetTypeName + "{\n")
	g.writeStructLiteral(buf, targetStruct, ownerStruct, "t")
	buf.WriteString("}\n}\n")
}

// writeStructLiteral writes field assignments for a struct literal, delegating
// each field to writeFieldAssignment. sourceStruct is the struct sourceExpr
// refers to, or nil when it is unknown.
func (g *GenGettersGenerator) writeStructLiteral(buf *bytes.Buffer, targetStruct, sourceStruct *types.Struct, sourceExpr string) {
	for field := range targetStruct.Fields() {
		g.writeFieldAssignment(buf, field, structFieldType(sourceStruct, field.Name()), sourceExpr)
	}
}

// writeFieldAssignment writes a single field assignment in a struct literal.
// A field whose source has the same type is assigned directly (#371). Otherwise,
// for named struct types, it recursively constructs a nested struct literal,
// taking its address when the target field is a pointer. Other types are
// assigned directly from the source expression.
func (g *GenGettersGenerator) writeFieldAssignment(buf *bytes.Buffer, field *types.Var, sourceType types.Type, sourceExpr string) {
	fieldName := field.Name()
	fieldExpr := sourceExpr + "." + fieldName

	nestedStruct := underlyingStruct(field.Type())
	if nestedStruct == nil || sameGeneratedType(sourceType, field.Type()) {
		buf.WriteString(fieldName + ": " + fieldExpr + ",\n")

		return
	}

	literal := g.typeName(field.Type()) + "{\n"
	if _, isPointer := field.Type().(*types.Pointer); isPointer {
		literal = "&" + literal
	}

	buf.WriteString(fieldName + ": " + literal)
	g.writeStructLiteral(buf, nestedStruct, underlyingStruct(sourceType), fieldExpr)
	buf.WriteString("},\n")
}

// sameGeneratedType reports whether a and b denote the same Go type in the
// generated code. Each fragment builds its own *types.Named for a fragment type
// it references, so two fields of type *MetaDetails are not types.Identical;
// a qualified name names exactly one declaration, so the type strings decide.
func sameGeneratedType(a, b types.Type) bool {
	if a == nil || b == nil {
		return false
	}

	return types.Identical(a, b) || types.TypeString(a, nil) == types.TypeString(b, nil)
}

// structFieldType returns the type of the field named name in s, or nil when s
// is nil or has no such field.
func structFieldType(s *types.Struct, name string) types.Type {
	if s == nil {
		return nil
	}

	for field := range s.Fields() {
		if field.Name() == name {
			return field.Type()
		}
	}

	return nil
}

// returnTypeName renders the Go type of a getter's return value.
//
// Arguments:
//   - t: the field type
//   - nested: true when t is an element of a pointer, slice, or map, in which
//     case named types are not wrapped in a pointer
//
// Returns:
//   - string: the Go type expression, qualified with the package name when the
//     type comes from another package
//   - error: non-nil when t is a kind the generator cannot express
//
// Preconditions:
//   - none
//
// Postconditions:
//   - a named type at the top level is returned as a pointer so that getters
//     can be chained without nil checks
func (g *GenGettersGenerator) returnTypeName(t types.Type, nested bool) (string, error) {
	switch it := t.(type) {
	case *types.Basic:
		return it.String(), nil
	case *types.Pointer:
		elem, err := g.returnTypeName(it.Elem(), true)
		if err != nil {
			return "", err
		}

		return "*" + elem, nil
	case *types.Slice:
		elem, err := g.returnTypeName(it.Elem(), true)
		if err != nil {
			return "", err
		}

		return "[]" + elem, nil
	case *types.Named:
		// Prefer gqlgen's import-aware printer so getters agree with struct
		// field tags when two packages share a name (same client package name
		// as an autobound import, or two autobound packages both named
		// "domain"). Fall back to the name comparison when no render is in
		// progress (unit tests).
		var name string
		if templates.CurrentImports != nil {
			name = templates.CurrentImports.LookupType(it)
		} else {
			name = it.Obj().Name()
			if it.Obj().Pkg() != nil && it.Obj().Pkg().Name() != g.ClientPackageName {
				name = namedTypeString(it)
			}
		}

		if nested {
			return name, nil
		}

		return "*" + name, nil
	case *types.Interface:
		return "any", nil
	case *types.Map:
		key, err := g.returnTypeName(it.Key(), true)
		if err != nil {
			return "", err
		}

		elem, err := g.returnTypeName(it.Elem(), true)
		if err != nil {
			return "", err
		}

		return "map[" + key + "]" + elem, nil
	case *types.Alias:
		return g.returnTypeName(it.Underlying(), nested)
	default:
		return "", fmt.Errorf("unsupported type %s (%T) in getter return type", t, t)
	}
}

// typeName extracts the short type name from a types.Type.
func (g *GenGettersGenerator) typeName(t types.Type) string {
	switch it := t.(type) {
	case *types.Named:
		s := strings.Split(it.String(), ".")
		return s[len(s)-1]
	case *types.Pointer:
		return g.typeName(it.Elem())
	default:
		return t.String()
	}
}

// underlyingStruct returns the *types.Struct if t is a named struct type, nil otherwise.
func underlyingStruct(t types.Type) *types.Struct {
	// Unwrap pointer
	if ptr, ok := t.(*types.Pointer); ok {
		t = ptr.Elem()
	}

	named, ok := t.(*types.Named)
	if !ok {
		return nil
	}

	st, ok := named.Underlying().(*types.Struct)
	if !ok {
		return nil
	}

	return st
}

func namedTypeString(named *types.Named) string {
	// オブジェクトからパッケージ情報を取得
	pkg := named.Obj().Pkg()

	// パッケージ情報がない場合、型名のみを返す
	if pkg == nil {
		return named.Obj().Name()
	}

	// パッケージ名と型名を結合して返す
	return fmt.Sprintf("%s.%s", pkg.Name(), named.Obj().Name())
}
