package gosrc

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"

	toolsimports "golang.org/x/tools/imports"
)

// generatedHeader は、生成したファイルの先頭に書くコメント。
const generatedHeader = "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n"

// WriteFile は、パッケージ packageName の Go のファイル filename を書き出す。body は package 句と
// import 宣言より後ろの宣言で、imports は body が参照するパッケージである。
//
//   - imports のうち、body が名前で参照していないものは書かない
//   - gofmt で整形し、import を標準パッケージとそれ以外に分けて並べる
//   - 内容が今あるファイルと同じなら書かず、更新時刻を変えない
//
// body が Go のソースとして読めないときは、整形せずにそのまま書いて nil を返す。読めないコードを
// 出力として採用しないのは、呼び出し側の出力の検査 (構文エラーの位置と行を添えて報告する) の役目である。
func WriteFile(filename, packageName string, imports *Imports, body []byte) error {
	var src bytes.Buffer
	src.WriteString(generatedHeader + "\npackage " + packageName + "\n\n")
	if lines := imports.lines(usedQualifiers(body, imports)); lines != "" {
		src.WriteString("import (\n" + lines + ")\n")
	}
	src.Write(body)

	formatted, err := toolsimports.Process(filename, src.Bytes(), &toolsimports.Options{
		Fragment:   false,
		AllErrors:  false,
		Comments:   true,
		TabIndent:  true,
		TabWidth:   8,
		FormatOnly: true,
	})
	if err != nil {
		formatted = src.Bytes()
	}

	if existing, err := os.ReadFile(filename); err == nil && bytes.Equal(existing, formatted) {
		return nil
	}

	// 生成するソースは、リポジトリの他のソースと同じ権限で書く
	if err := os.MkdirAll(filepath.Dir(filename), 0o755); err != nil {
		return fmt.Errorf("create directory of %s: %w", filename, err)
	}
	if err := os.WriteFile(filename, formatted, 0o644); err != nil { //nolint:gosec // 生成するソースは、他のソースと同じ権限にする
		return fmt.Errorf("write %s: %w", filename, err)
	}

	return nil
}

// usedQualifiers は、body が x.Name の形で参照している x の名前の集合を返す。
//
// x がパッケージではなく変数のこともあるが、区別しない。生成するコードでは、名前を直接書いて参照する
// パッケージ (Imports.Reserve) と同じ名前の変数を使わないため、使っていない import を残すことはない。
//
// body を読めないときは、imports のすべての名前を返す (どの import も消さない)。
func usedQualifiers(body []byte, imports *Imports) map[string]bool {
	used := make(map[string]bool, len(imports.specs))

	file, err := parser.ParseFile(token.NewFileSet(), "", append([]byte("package p\n"), body...), parser.SkipObjectResolution)
	if err != nil {
		for _, spec := range imports.specs {
			used[spec.alias] = true
		}

		return used
	}

	ast.Inspect(file, func(node ast.Node) bool {
		if selector, ok := node.(*ast.SelectorExpr); ok {
			if x, ok := selector.X.(*ast.Ident); ok {
				used[x.Name] = true
			}
		}

		return true
	})

	return used
}
