package gosrc

import (
	"go/types"
	"os"
	"path/filepath"
	"testing"
	"time"

	"github.com/google/go-cmp/cmp"
	"github.com/google/go-cmp/cmp/cmpopts"
)

func TestWriteFile(t *testing.T) {
	t.Parallel()

	// existingModTime は、先に置いたファイルの更新時刻。書き直したかどうかを、この時刻から変わったかで見分ける
	existingModTime := time.Date(2020, 1, 1, 0, 0, 0, 0, time.UTC)

	type fields struct {
		// existing は、出力先に先に置いてあるファイルの内容。空なら、ファイルもディレクトリも無い
		existing string
	}

	type args struct {
		// reserved は Imports.Reserve で、qualified は Imports.Qualifier で加える import
		reserved  []reservation
		qualified []*types.Package
		body      string
	}

	type want struct {
		content string
		// written は、ファイルを書いたか (先に置いたファイルの更新時刻が変わったか、ファイルを新しく作ったか)
		written bool
		err     error
	}

	tests := []struct {
		name   string
		fields fields
		args   args
		want   want
	}{
		{
			name: "使っているimportを標準パッケージとそれ以外に分けて書きgofmtで整形する",
			args: args{
				reserved: []reservation{
					{path: "github.com/Yamashou/gqlgenc/v3/client", name: "client"},
					{path: "github.com/99designs/gqlgen/graphql", name: "graphql"},
					{path: "encoding/json/v2", name: "json"},
					{path: "encoding/json/jsontext", name: "jsontext"},
				},
				body: "\ntype Vars struct {\nID string `json:\"id\"`\n}\nvar Op = client.Operation[client.Query, Vars, jsontext.Value]{Name: \"Op\"}\nvar Opt = json.Deterministic(true)\n",
			},
			want: want{
				// graphql は body が参照していないので書かない。json は import パスの末尾 (v2) と名前が違うので名前を書く
				content: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\nimport (\n\t\"encoding/json/jsontext\"\n\tjson \"encoding/json/v2\"\n\n\t\"github.com/Yamashou/gqlgenc/v3/client\"\n)\n\ntype Vars struct {\n\tID string `json:\"id\"`\n}\n\nvar Op = client.Operation[client.Query, Vars, jsontext.Value]{Name: \"Op\"}\nvar Opt = json.Deterministic(true)\n",
				written: true,
			},
		},
		{
			// 境界値: import が 1 つも無い
			name: "importが無ければimport宣言を書かない",
			args: args{
				body: "\nconst GetUserDocument = `query GetUser { user { id } }`\n",
			},
			want: want{
				content: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\nconst GetUserDocument = `query GetUser { user { id } }`\n",
				written: true,
			},
		},
		{
			name: "どのimportも使っていなければimport宣言を書かない",
			args: args{
				reserved: []reservation{{path: "github.com/Yamashou/gqlgenc/v3/client", name: "client"}},
				body:     "\ntype User struct {\nID string\n}\n",
			},
			want: want{
				content: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\ntype User struct {\n\tID string\n}\n",
				written: true,
			},
		},
		{
			name: "別名を付けたimportは別名を書く",
			args: args{
				qualified: []*types.Package{
					types.NewPackage("example.com/shop/domain", "domain"),
					types.NewPackage("example.com/billing/domain", "domain"),
				},
				body: "\ntype Order struct {\nStatus *domain.Status\nInvoices []domain1.Invoice\n}\n",
			},
			want: want{
				content: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\nimport (\n\tdomain1 \"example.com/billing/domain\"\n\t\"example.com/shop/domain\"\n)\n\ntype Order struct {\n\tStatus   *domain.Status\n\tInvoices []domain1.Invoice\n}\n",
				written: true,
			},
		},
		{
			// 読めないコードを出力として採用しないのは、呼び出し側の出力の検査の役目
			name: "bodyがGoのソースとして読めなければ整形せずに書く",
			args: args{
				reserved: []reservation{{path: "github.com/Yamashou/gqlgenc/v3/client", name: "client"}},
				body:     "\ntype User struct {\nID *invalid type\n}\n",
			},
			want: want{
				content: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\nimport (\n\"github.com/Yamashou/gqlgenc/v3/client\"\n)\n\ntype User struct {\nID *invalid type\n}\n",
				written: true,
			},
		},
		{
			name: "今あるファイルと内容が違えば書き直す",
			fields: fields{
				existing: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\ntype User struct {\n\tID string\n}\n",
			},
			args: args{
				body: "\ntype User struct {\nID string\nName string\n}\n",
			},
			want: want{
				content: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\ntype User struct {\n\tID   string\n\tName string\n}\n",
				written: true,
			},
		},
		{
			// 生成し直しても、内容の変わらないファイルの更新時刻を変えない
			name: "今あるファイルと内容が同じなら書かない",
			fields: fields{
				existing: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\ntype User struct {\n\tID string\n}\n",
			},
			args: args{
				body: "\ntype User struct {\nID string\n}\n",
			},
			want: want{
				content: "// Code generated by github.com/Yamashou/gqlgenc, DO NOT EDIT.\n\npackage gen\n\ntype User struct {\n\tID string\n}\n",
				written: false,
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			// 出力先のディレクトリは、先に置くファイルが無ければ作らない
			filename := filepath.Join(t.TempDir(), "gen", "query_gen.go")
			if tt.fields.existing != "" {
				if err := os.MkdirAll(filepath.Dir(filename), 0o750); err != nil {
					t.Fatalf("failed to create directory: %v", err)
				}
				if err := os.WriteFile(filename, []byte(tt.fields.existing), 0o600); err != nil {
					t.Fatalf("failed to write existing file: %v", err)
				}
				if err := os.Chtimes(filename, existingModTime, existingModTime); err != nil {
					t.Fatalf("failed to set mod time: %v", err)
				}
			}

			imports := newTestImports(t, "example.com/shop/gen", tt.args.reserved, tt.args.qualified)

			err := WriteFile(filename, "gen", imports, []byte(tt.args.body))

			if diff := cmp.Diff(tt.want.err, err, cmpopts.EquateErrors()); diff != "" {
				t.Errorf("error diff(-want +got): %s", diff)
			}

			content, err := os.ReadFile(filename)
			if err != nil {
				t.Fatalf("failed to read output: %v", err)
			}
			if diff := cmp.Diff(tt.want.content, string(content)); diff != "" {
				t.Errorf("content diff(-want +got): %s", diff)
			}

			info, err := os.Stat(filename)
			if err != nil {
				t.Fatalf("failed to stat output: %v", err)
			}
			if diff := cmp.Diff(tt.want.written, !info.ModTime().Equal(existingModTime)); diff != "" {
				t.Errorf("written diff(-want +got): %s", diff)
			}
		})
	}
}
