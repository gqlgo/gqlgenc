// outputFiles is what the output path and the backup path hold; "" is no file.
type outputFiles struct {
	output string
	backup string
}

// write creates the files of outputFiles for the output at path.
func (f outputFiles) write(t *testing.T, path string) {
	t.Helper()

	if f.output != "" {
		require.NoError(t, os.WriteFile(path, []byte(f.output), 0o600))
	}

	if f.backup != "" {
		require.NoError(t, os.WriteFile(path+outputBackupSuffix, []byte(f.backup), 0o600))
	}
}

// readOutputFiles reads what the output at path and its backup path hold.
func readOutputFiles(t *testing.T, path string) outputFiles {
	t.Helper()

	read := func(name string) string {
		content, err := os.ReadFile(name)
		if os.IsNotExist(err) {
			return ""
		}

		require.NoError(t, err)

		return string(content)
	}

	return outputFiles{output: read(path), backup: read(path + outputBackupSuffix)}
}

// commitOutputBackup commits one backup the way Generate does.
func commitOutputBackup(b *outputBackup) error {
	return commitOutputBackups([]*outputBackup{b})
}

// TestOutputBackup_transitions walks every transition of outputBackupState and
// checks the files each one leaves.
func TestOutputBackup_transitions(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		// before is the directory when Generate starts.
		before outputFiles
		// generated is what generation writes to the output path; "" writes nothing.
		generated string
		// settleWith is the transition out of the unsettled state.
		settleWith      func(b *outputBackup) error
		wantBackedUp    outputBackupState
		wantSettled     outputBackupState
		wantAfterSettle outputFiles
	}{
		{
			name:            "PreviousSaved to Committed keeps different generated bytes",
			before:          outputFiles{output: "old"},
			generated:       "new",
			settleWith:      commitOutputBackup,
			wantBackedUp:    outputBackupStatePreviousSaved,
			wantSettled:     outputBackupStateCommitted,
			wantAfterSettle: outputFiles{output: "new"},
		},
		{
			name:            "PreviousSaved to Committed puts identical bytes back",
			before:          outputFiles{output: "old"},
			generated:       "old",
			settleWith:      commitOutputBackup,
			wantBackedUp:    outputBackupStatePreviousSaved,
			wantSettled:     outputBackupStateCommitted,
			wantAfterSettle: outputFiles{output: "old"},
		},
		{
			name:            "PreviousSaved to Committed drops the backup when nothing was generated",
			before:          outputFiles{output: "old"},
			settleWith:      commitOutputBackup,
			wantBackedUp:    outputBackupStatePreviousSaved,
			wantSettled:     outputBackupStateCommitted,
			wantAfterSettle: outputFiles{},
		},
		{
			name:            "PreviousSaved to Restored replaces a partial output",
			before:          outputFiles{output: "old"},
			generated:       "partial",
			settleWith:      (*outputBackup).restore,
			wantBackedUp:    outputBackupStatePreviousSaved,
			wantSettled:     outputBackupStateRestored,
			wantAfterSettle: outputFiles{output: "old"},
		},
		{
			name:            "a backup left by an interrupted run is adopted as PreviousSaved",
			before:          outputFiles{backup: "old"},
			generated:       "partial",
			settleWith:      (*outputBackup).restore,
			wantBackedUp:    outputBackupStatePreviousSaved,
			wantSettled:     outputBackupStateRestored,
			wantAfterSettle: outputFiles{output: "old"},
		},
		{
			name:            "NoPrevious to Committed keeps the generated output",
			before:          outputFiles{},
			generated:       "new",
			settleWith:      commitOutputBackup,
			wantBackedUp:    outputBackupStateNoPrevious,
			wantSettled:     outputBackupStateCommitted,
			wantAfterSettle: outputFiles{output: "new"},
		},
		{
			name:            "NoPrevious to Restored deletes a partial output",
			before:          outputFiles{},
			generated:       "partial",
			settleWith:      (*outputBackup).restore,
			wantBackedUp:    outputBackupStateNoPrevious,
			wantSettled:     outputBackupStateRestored,
			wantAfterSettle: outputFiles{},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			path := filepath.Join(t.TempDir(), "client.go")
			tt.before.write(t, path)

			cfg := &config.Config{GQLConfig: &gqlgenconfig.Config{}}

			backup, err := backupOutput(cfg, gqlgenconfig.PackageConfig{Filename: path})
			require.NoError(t, err)
			require.Equal(t, tt.wantBackedUp, backup.state)
			require.Empty(t, readOutputFiles(t, path).output, "the output is moved aside before generation")

			outputFiles{output: tt.generated}.write(t, path)

			require.NoError(t, tt.settleWith(backup))
			require.Equal(t, tt.wantSettled, backup.state)
			require.Equal(t, tt.wantAfterSettle, readOutputFiles(t, path))

			// Committed and Restored are final: the restore deferred by Generate
			// and a second commit leave the result alone.
			require.NoError(t, backup.restore())
			require.NoError(t, commitOutputBackup(backup))
			require.Equal(t, tt.wantSettled, backup.state)
			require.Equal(t, tt.wantAfterSettle, readOutputFiles(t, path))
		})
	}
}

func TestOutputBackup_settleRejectsInvalidTransitions(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name       string
		state      outputBackupState
		finalState outputBackupState
	}{
		{name: "Committed is final", state: outputBackupStateCommitted, finalState: outputBackupStateRestored},
		{name: "Restored is final", state: outputBackupStateRestored, finalState: outputBackupStateCommitted},
		{name: "PreviousSaved is not a final state", state: outputBackupStateNoPrevious, finalState: outputBackupStatePreviousSaved},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			backup := &outputBackup{path: "client.go", state: tt.state}

			require.Panics(t, func() { backup.settle(tt.finalState) })
			require.Equal(t, tt.state, backup.state)
		})
	}
}

// TestCommitOutputBackups_failureCommitsNothing checks that a commit that
// cannot read the backup of the second output leaves the first one restorable,
// so that a failed Generate puts every output back.
func TestCommitOutputBackups_failureCommitsNothing(t *testing.T) {
	t.Parallel()

	if runtime.GOOS == "windows" || os.Geteuid() == 0 {
		t.Skip("needs a file the process cannot read")
	}

	dir := t.TempDir()
	clientPath := filepath.Join(dir, "client.go")
	modelPath := filepath.Join(dir, "models_gen.go")

	outputFiles{output: "old client"}.write(t, clientPath)
	outputFiles{output: "old model"}.write(t, modelPath)

	cfg := &config.Config{GQLConfig: &gqlgenconfig.Config{}}

	clientBackup, err := backupOutput(cfg, gqlgenconfig.PackageConfig{Filename: clientPath})
	require.NoError(t, err)

	modelBackup, err := backupOutput(cfg, gqlgenconfig.PackageConfig{Filename: modelPath})
	require.NoError(t, err)

	backups := []*outputBackup{clientBackup, modelBackup}

	outputFiles{output: "new client"}.write(t, clientPath)
	outputFiles{output: "new model"}.write(t, modelPath)

	require.NoError(t, os.Chmod(modelBackup.bakPath, 0o000))

	require.ErrorContains(t, commitOutputBackups(backups), "read output backup")
	require.Equal(t, outputBackupStatePreviousSaved, clientBackup.state)
	require.Equal(t, outputBackupStatePreviousSaved, modelBackup.state)

	// The restore deferred by Generate.
	require.NoError(t, restoreOutputBackups(backups))
	require.NoError(t, os.Chmod(modelPath, 0o600))

	require.Equal(t, outputFiles{output: "old client"}, readOutputFiles(t, clientPath))
	require.Equal(t, outputFiles{output: "old model"}, readOutputFiles(t, modelPath))
}
